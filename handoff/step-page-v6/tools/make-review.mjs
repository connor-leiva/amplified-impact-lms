// Builds src/components/ReviewSection.jsx (MOCKUP-ONLY) from the mockup's own MOCKUP bar and "Text styles" section,
// so the harness renders them byte for byte. Inline styles get the step page's token names (var(--s5) -> var(--sp-s5)).
//   node tools/make-review.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const H = readFileSync(new URL('../mockup/step-2.html', import.meta.url), 'utf8');
const cut = (start, end) => { const a = H.indexOf(start); const b = H.indexOf(end, a) + end.length; if (a < 0) throw new Error('missing ' + start); return H.slice(a, b); };
const tokenized = (html) => html.replace(/var\(--(?!sp-|aim-)([a-z0-9-]+)\)/g, 'var(--sp-$1)');
const FLAG = tokenized(cut('<div class="mock-flag">', '</div>'));
const HTML = tokenized(cut('<section class="review', '</section>'));
const src = `// MOCKUP-ONLY. GENERATED by tools/make-review.mjs from mockup/step-2.html: the black MOCKUP bar and the
// "Text styles for long steps" review block, Week Builder preview and button gallery, kept verbatim so the harness
// can be diffed against the mockup's full page. Do NOT ship this to learners: in the LMS the real content comes
// from the Tiptap rich text (#200) and these styles live in step-page.css as .rt-* classes.
const HTML = ${JSON.stringify(HTML)};
const FLAG = ${JSON.stringify(FLAG)};

export function MockFlag() {
  return <div style={{ display: 'contents' }} dangerouslySetInnerHTML={{ __html: FLAG }} />;
}

export function ReviewSection() {
  const onClick = (e) => {
    const b = e.target.closest('[data-copy]'); if (!b) return;
    const text = b.closest('.copyblock')?.querySelector('pre')?.textContent || '';
    navigator.clipboard?.writeText(text).catch(() => {});
    const spans = [...b.querySelectorAll('.aim-roll > span')];
    const old = spans[0].textContent; spans.forEach((s) => { s.textContent = 'Copied'; });
    setTimeout(() => spans.forEach((s) => { s.textContent = old; }), 1400);
  };
  // display:contents keeps the wrapper out of layout, so .main's flex gap sees the <section> itself.
  return <div style={{ display: 'contents' }} onClick={onClick} dangerouslySetInnerHTML={{ __html: HTML }} />;
}
`;
writeFileSync(new URL('../src/components/ReviewSection.jsx', import.meta.url), src);
console.log('ReviewSection.jsx: section', HTML.length, 'chars, flag', FLAG.length);
