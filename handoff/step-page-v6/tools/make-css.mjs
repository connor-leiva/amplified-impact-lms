// Generates src/step-page.tokens.css and src/step-page.css from the mockup's own <style> block
// (mockup/step-2.html, the v5 mockup that matches interaction-demo.mp4). `node tools/make-css.mjs`
// Values are copied verbatim; only names change (--x -> --sp-x) and raw colours in rules become tokens.
import { readFileSync, writeFileSync } from 'node:fs';
const HTML = readFileSync(new URL('../mockup/step-2.html', import.meta.url), 'utf8');
const A = HTML.slice(HTML.indexOf('<style>') + 7, HTML.indexOf('</style>')).replace(/^\n/, '');
const rootStart = A.indexOf(':root{'), rootEnd = A.indexOf('\n}', rootStart) + 2;
const root = A.slice(rootStart + 6, rootEnd - 2);
let rules = A.slice(rootEnd);
const names = [...root.matchAll(/--([a-z0-9-]+):/g)].map(m => m[1]);
// shared repo tokens (apps/web/src/styles/r2.css) whose value is byte-identical: used with the mockup value as fallback
const MAP = { forest: '--r2-for', 'energy-bright': '--r2-mint', energy: '--r2-energy', surface: '--r2-sf', black: '--r2-wm-ink' };
const ren = s => s.replace(/var\(--([a-z0-9-]+)\)/g, (m, n) => names.includes(n) ? `var(--sp-${n})` : m);
// raw colours in rules -> new tokens (order matters: longest first)
const RAW = [
  ['rgb(10 13 12 / .85)', 'ink-85'], ['rgb(10 13 12 / .82)', 'ink-82'], ['rgb(10 13 12 / .78)', 'ink-78'],
  ['rgb(10 13 12 / .72)', 'ink-72'], ['rgb(10 13 12 / .6)', 'ink-3'], ['rgb(10 13 12 / .45)', 'ink-45'], ['rgb(10 13 12 / .35)', 'ink-35'],
  ['rgb(10 13 12 / .25)', 'ink-25'], ['rgb(10 13 12 / .2)', 'line-2'], ['rgb(10 13 12 / .08)', 'ink-08'],
  ['rgb(31 77 64 / .18)', 'forest-18'], ['rgb(245 245 242 / .16)', 'on-forest-16'],
  ['rgb(245 245 242 / .82)', 'on-forest-82'], ['rgb(245 245 242 / .1)', 'on-forest-10'],
  ['#fff', 'white'], ['#000', 'mask'],
];
const extra = { 'ink-85':'rgb(10 13 12 / .85)','ink-82':'rgb(10 13 12 / .82)','ink-78':'rgb(10 13 12 / .78)','ink-72':'rgb(10 13 12 / .72)',
  'ink-45':'rgb(10 13 12 / .45)','ink-35':'rgb(10 13 12 / .35)','ink-25':'rgb(10 13 12 / .25)','ink-08':'rgb(10 13 12 / .08)','forest-18':'rgb(31 77 64 / .18)',
  'on-forest-16':'rgb(245 245 242 / .16)','on-forest-82':'rgb(245 245 242 / .82)','on-forest-10':'rgb(245 245 242 / .1)',
  white:'#fff', mask:'#000 /* mask alpha only, never painted */' };
rules = ren(rules);
for (const [raw, tok] of RAW) rules = rules.split(raw).join(`var(--sp-${tok})`);
rules = rules.split(',white)').join(',var(--sp-white))');
// scope the mockup's element-level rules to the step page, at zero added specificity
const SCOPE = [
  ['*{box-sizing:border-box}', ':where([data-step-page]),:where([data-step-page]) *{box-sizing:border-box}'],
  ['html{scroll-behavior:smooth;scroll-padding-top:24px}', 'html:has([data-step-page]){scroll-behavior:smooth;scroll-padding-top:24px}'],
  ['body{margin:0;', 'html:has([data-step-page]) body{margin:0;background:var(--sp-bone)}\n[data-step-page]{'],
  ['h1,h2,h3,p{margin:0}', ':where([data-step-page]) :is(h1,h2,h3,p){margin:0}'],
  ['button{font:inherit;color:inherit}', ':where([data-step-page]) button{font:inherit;color:inherit}'],
  ['a{color:inherit}', ':where([data-step-page]) a{color:inherit}'],
  ['svg{display:block}', ':where([data-step-page]) svg{display:block}'],
  ['  html{scroll-behavior:auto}', '  html:has([data-step-page]){scroll-behavior:auto}'],
];
for (const [a, b] of SCOPE) { if (!rules.includes(a)) throw new Error('missing ' + a); rules = rules.replace(a, b); }
// drop @font-face (repo has styles/geist.css; the harness loads its own copy)
let header = A.slice(0, rootStart);
const tokens = root.split('\n').map(l => l.replace(/--([a-z0-9-]+):([^;]+);/g, (m, n, v) => {
  v = ren(v.trim());
  if (MAP[n]) v = `var(${MAP[n]}, ${v})`;
  return `--sp-${n}:${v};`;
})).join('\n');
const extraLines = Object.entries(extra).map(([k, v]) => `  --sp-${k}:${v};`).join('\n');
const tok = `/* Step page tokens (v5 video-parity handoff). GENERATED by tools/make-css.mjs from mockup/step-2.html.
   Values are the mockup's, verbatim. Names carry --sp- because --ink, --line, --s1 etc. already mean other things in the LMS.
   Where the LMS already has a byte-identical shared token (styles/r2.css) it is used first, with the mockup value as fallback.
   Global stylesheet (not a module): scripts/check-css-colors.mjs only scans *.module.css, so raw values may live here. */
html:has([data-step-page]),[data-step-page]{
${tokens.replace(/^\s*interpolate-size:allow-keywords;\s*$/m, '')}
${extraLines}
}
:root{interpolate-size:allow-keywords}
`;
writeFileSync(new URL('../src/step-page.tokens.css', import.meta.url), tok);
const css = `/* Step page styles (v5 video-parity handoff). GENERATED by tools/make-css.mjs from mockup/step-2.html.
   Every rule and value is the mockup's; colours are only var(--sp-*) from step-page.tokens.css.
   The mockup's html/body rules are kept as written (html{} and body{} at the top) so the page renders identically. */
${rules.trim()}

/* OPTIONAL, OFF by default: Connor's Nov 19 phone-rail note: at 640px and narrower the current pill shows
   only its number. It is NOT in the mockup or the video, so it only applies when <StepPage railPhone="number">
   sets data-rail-phone="number". Turning it on changes phone-390 pixels. */
@media (max-width:640px){
  [data-rail-phone="number"] .stp[aria-current="step"] .stp-t{display:none}
  [data-rail-phone="number"] .stp[aria-current="step"]{padding:0 7px}
}
`;
writeFileSync(new URL('../src/step-page.css', import.meta.url), css);
writeFileSync(new URL('../harness/public/fonts.css', import.meta.url), header.replace(/url\('fonts\//g, "url('fonts/"));
// verify: no raw colour left in rules
const left = css.split('\n').filter(l => /#[0-9a-f]{3,8}\b|rgba?\(|hsla?\(|(?<![-\w])(white|black)(?![-\w])/i.test(l));
console.log('tokens', names.length + Object.keys(extra).length, 'raw-colour lines left:', left.length); left.forEach(l => console.log('  ', l.slice(0, 160)));
