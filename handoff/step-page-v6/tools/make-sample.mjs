// Builds src/sample-data.js from the mockup's own content (step-2.html), so the harness renders the same words.
import { readFileSync, writeFileSync } from 'node:fs';
const H = readFileSync(new URL('../mockup/step-2.html', import.meta.url), 'utf8');
const grab = n => JSON.parse(H.match(new RegExp(`const ${n} = (\\[.*?\\]);\\n`))[1]);
const un = s => s.replace(/&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const chapters = grab('CHAPTERS').map(c => ({ t: c.t, label: un(c.label) }));
const cues = grab('CUES').map(c => ({ s: c.s, e: c.e, text: un(c.text) }));
writeFileSync(new URL('../src/sample-cues.js', import.meta.url),
  '// GENERATED by tools/make-sample.mjs from mockup/step-2.html (the orientation VTT). Do not hand-edit.\n' +
  `export const chapters = ${JSON.stringify(chapters, null, 1)};\nexport const cues = ${JSON.stringify(cues)};\n`);
console.log(chapters.length, 'chapters', cues.length, 'cues');
