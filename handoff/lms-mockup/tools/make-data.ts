// Writes ../buyer-data.js: the Skill Library and the buyer's pages' content as the $37 buyer mockup draws them, from the
// repo's own sources, so no title, line or step in the mockup is typed by hand, and the mockup and the build (D-241)
// read the same words.
//
//   titles, summaries, sets, files   packages/core/src/skills.ts (SKILL_CATALOG) and grok-templates.ts (GROK_TEMPLATES)
//   free                              packages/core/src/skills.ts (FREE_SKILLS)
//   the problem, what it does, who   apps/web/src/library/content.ts (leadFor, the lead every card says first)
//   setup steps per AI app           apps/web/dist-private/skill-guides.json (the guided setup, written by the web build)
//   plans, training, office hours,   apps/web/src/routes/learn/buyer/content.ts (the build's own module: the offer, the
//   the AI Accelerator                 Agent Plan, the Accelerator's page and Week 0's steps)
//
// Run from the repo root, after `pnpm --filter @ai/web build:fixture` has written the guides file:
//   pnpm --filter @ai/api exec tsx ../../handoff/lms-mockup/tools/make-data.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FREE_SKILLS, SKILL_CATALOG } from '../../../packages/core/src/skills';
import { GROK_TEMPLATES } from '../../../packages/core/src/grok-templates';
import { leadFor } from '../../../apps/web/src/library/content';
import { ACCEL, ACCELERATOR_HREF, AGENT_PLAN_UP, OFFICE, PLANS, TRAINING } from '../../../apps/web/src/routes/learn/buyer/content';

interface Guide { slug: string; intro: string; lanes: { id: string; label: string; steps: { title: string }[] }[] }
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const guidesFile = JSON.parse(readFileSync(resolve(root, 'apps/web/dist-private/skill-guides.json'), 'utf8')) as {
  guides: Record<string, Guide> | Guide[];
};
const guides = Array.isArray(guidesFile.guides) ? guidesFile.guides : Object.values(guidesFile.guides);
const guideOf = (page: string) => guides.find((g) => g.slug === page);

// In the API's order (`GET /api/skills`: release, then title; every skill shares the launch release).
const rows = [
  ...SKILL_CATALOG.map((s) => ({ id: s.id, title: s.title, sets: s.sets, page: s.page ?? s.id, files: Object.keys(s.files) })),
  ...GROK_TEMPLATES.map((g) => ({ id: g.id, title: g.title, sets: g.sets, page: g.id, files: ['grok'] })),
].map((r) => {
  const lead = leadFor(r.page);
  const guide = guideOf(r.page);
  if (!lead || !guide) throw new Error(`${r.id}: no lead or no guide`);
  return {
    id: r.id,
    t: r.title,
    s: r.sets,
    f: FREE_SKILLS.includes(r.id) ? 1 : 0,
    role: lead.forRole ?? 'Anyone',
    pr: lead.problem,
    o: lead.outcome,
    files: r.files,
    intro: guide.intro,
    lanes: guide.lanes.map((l) => ({ id: l.id, label: l.label, steps: l.steps.map((s) => s.title) })),
  };
}).sort((a, b) => a.t.localeCompare(b.t));

writeFileSync(
  resolve(here, '../buyer-data.js'),
  `/* GENERATED by tools/make-data.ts from the repo's catalogs, leads and guides, and the build's buyer content. Do not edit by hand. */\n` +
    `window.CATALOG = ${JSON.stringify(rows)};\n` +
    `window.BUYER = ${JSON.stringify({ plans: PLANS, agentPlan: AGENT_PLAN_UP, training: TRAINING, office: OFFICE, accel: ACCEL, accelHref: ACCELERATOR_HREF })};\n`,
);
console.log(`buyer-data.js: ${rows.length} skills`);
