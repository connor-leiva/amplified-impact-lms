// Writes ../buyer-data.js: the Skill Library as the $37 buyer mockup draws it, from the repo's own sources, so no
// title, line or step in the mockup is typed by hand.
//
//   titles, summaries, sets, files   packages/core/src/skills.ts (SKILL_CATALOG) and grok-templates.ts (GROK_TEMPLATES)
//   free                              packages/core/src/skills.ts (FREE_SKILLS)
//   the problem, what it does, who   apps/web/src/library/content.ts (leadFor, the lead every card says first)
//   setup steps per AI app           apps/web/dist-private/skill-guides.json (the guided setup, written by the web build)
//
// Run from the repo root, after `pnpm --filter @ai/web build:fixture` has written the guides file:
//   pnpm --filter @ai/api exec tsx ../../handoff/lms-mockup/tools/make-data.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FREE_SKILLS, SKILL_CATALOG } from '../../../packages/core/src/skills';
import { GROK_TEMPLATES } from '../../../packages/core/src/grok-templates';
import { leadFor } from '../../../apps/web/src/library/content';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const guidesFile = JSON.parse(readFileSync(resolve(root, 'apps/web/dist-private/skill-guides.json'), 'utf8')) as {
  guides: Record<string, { slug: string; intro: string; lanes: { id: string; steps: { title: string }[] }[] }> | { slug: string; intro: string; lanes: { id: string; steps: { title: string }[] }[] }[];
};
const guides = Array.isArray(guidesFile.guides) ? guidesFile.guides : Object.values(guidesFile.guides);
const guideOf = (page: string) => guides.find((g) => g.slug === page);

const rows = [
  ...SKILL_CATALOG.map((s) => ({ id: s.id, title: s.title, sets: s.sets, page: s.page ?? s.id, files: Object.keys(s.files) })),
  ...GROK_TEMPLATES.map((g) => ({ id: g.id, title: g.title, sets: g.sets, page: g.id, files: ['grok'] })),
].map((r) => {
  const lead = leadFor(r.page);
  const guide = guideOf(r.page);
  if (!lead || !guide) throw new Error(`${r.id}: no lead or no guide`);
  return {
    id: r.id,
    t: r.title,
    s: r.sets,
    f: FREE_SKILLS.includes(r.id) ? 1 : 0,
    role: lead.forRole ?? 'Anyone',
    pr: lead.problem,
    o: lead.outcome,
    files: r.files,
    intro: guide.intro,
    lanes: Object.fromEntries(guide.lanes.map((l) => [l.id, l.steps.map((s) => s.title)])),
  };
});

writeFileSync(
  resolve(here, '../buyer-data.js'),
  `/* GENERATED by tools/make-data.ts from the repo's catalogs, leads and guides. Do not edit by hand. */\nwindow.CATALOG = ${JSON.stringify(rows)};\n`,
);
console.log(`buyer-data.js: ${rows.length} skills`);
