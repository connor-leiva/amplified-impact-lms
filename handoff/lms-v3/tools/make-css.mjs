// Generates, from mockup/index.html (the source of truth):
//   src/lms.tokens.css         every colour, space, radius and type value as --sp-* (the step page's names)
//   src/lms.css                the page's rules, verbatim, with colours only as var(--sp-*)
//   src/mock-bar.css           MOCKUP-ONLY: the MOCKUP bar. Do not ship.
//   src/components/icons.generated.js   the icon sprite
//   src/components/mock.generated.js    MOCKUP-ONLY: the bar's markup, for MockBar.jsx
//   harness/public/fonts.css
//   node tools/make-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const H = readFileSync(new URL('../mockup/index.html', import.meta.url), 'utf8');
const A = H.slice(H.indexOf('<style>') + 7, H.indexOf('</style>')).replace(/^\n/, '');
const rootStart = A.indexOf(':root{'), rootEnd = A.indexOf('\n}', rootStart) + 2;
const root = A.slice(rootStart + 6, rootEnd - 2);
const fonts = A.slice(0, rootStart).split('\n').filter((l) => l.startsWith('@font-face')).join('\n') + '\n';
let rest = A.slice(rootEnd);
const names = [...root.matchAll(/--([a-z0-9-]+):/g)].map((m) => m[1]);
const ren = (s) => s.replace(/var\(--([a-z0-9-]+)\)/g, (m, n) => (names.includes(n) ? `var(--sp-${n})` : m));
// shared repo tokens (apps/web/src/styles/r2.css) with the same value: used first, the mockup value as fallback
const MAP = { forest: '--r2-for', 'energy-bright': '--r2-mint', energy: '--r2-energy', surface: '--r2-sf', black: '--r2-wm-ink' };
const tokens = root.split('\n').map((l) => l.replace(/--([a-z0-9-]+):([^;]+);/g, (m, n, v) => { v = ren(v.trim()); if (MAP[n]) v = `var(${MAP[n]}, ${v})`; return `--sp-${n}:${v};`; })).join('\n');
writeFileSync(new URL('../src/lms.tokens.css', import.meta.url), `/* LMS tokens. GENERATED by tools/make-css.mjs from mockup/index.html. The step page's token names and values
   (--sp-*), set wherever a data-ai root is (shell, week, schedule). Motion tokens are the brand's (--aim-*, ai-motion.css). */
html:has([data-ai]),[data-ai]{
${tokens}
}
:root{interpolate-size:allow-keywords}
`);
rest = rest.replace(':root{interpolate-size:allow-keywords}\n', '');
const SCOPE = [
  ['html{scroll-behavior:smooth;scroll-padding-top:24px}', 'html:has([data-ai]){scroll-behavior:smooth;scroll-padding-top:24px}'],
  ['body{margin:0;background:var(--bone)}', 'html:has([data-ai]) body{margin:0;background:var(--bone)}'],
  ['@media (prefers-reduced-motion:reduce){html{scroll-behavior:auto}', '@media (prefers-reduced-motion:reduce){html:has([data-ai]){scroll-behavior:auto}'],
];
for (const [a, b] of SCOPE) { if (!rest.includes(a)) throw new Error('missing ' + a); rest = rest.replace(a, b); }
const shellAt = rest.indexOf('/* @mock'), shellEnd = rest.indexOf('/* @end-mock */');
const page = ren(rest.slice(0, shellAt)).trim(), shell = ren(rest.slice(shellAt, shellEnd)).trim();
writeFileSync(new URL('../src/lms.css', import.meta.url), `/* LMS styles: shell (sh-*), week overview and shared pieces (wk-*), schedule (sc-*). GENERATED by tools/make-css.mjs from
   mockup/index.html. Every rule and value is the mockup's. Element rules are scoped to [data-ai], so nothing here touches the step page. */
${page}
`);
writeFileSync(new URL('../src/mock-bar.css', import.meta.url), `/* MOCKUP-ONLY. GENERATED. The black MOCKUP bar. Do NOT ship. */
${shell}
`);
writeFileSync(new URL('../harness/public/fonts.css', import.meta.url), fonts);
const raw = (page + shell).split('\n').filter((l) => /#[0-9a-f]{3,8}\b|rgba?\(|hsla?\(|(?<![-\w])(white|black)(?![-\w])/i.test(l));
// icons and the shell markup
const defs = H.slice(H.indexOf('<defs>') + 6, H.indexOf('</defs>')).trim();
writeFileSync(new URL('../src/components/icons.generated.js', import.meta.url), `// GENERATED by tools/make-css.mjs from mockup/index.html. Do not hand-edit.\nexport const SYMBOLS = ${JSON.stringify(defs)};\n`);
const cut = (a, b) => { const i = H.indexOf(a); const j = H.indexOf(b, i); if (i < 0 || j < 0) throw new Error('missing ' + a); return H.slice(i, j + b.length); };
const flag = cut('<div class="wkx-flag">', '</span></div>');
writeFileSync(new URL('../src/components/mock.generated.js', import.meta.url), `// MOCKUP-ONLY. GENERATED by tools/make-css.mjs from mockup/index.html. Do not hand-edit, do not ship.\nexport const FLAG = ${JSON.stringify(flag)};\n`);
console.log('tokens', names.length, '· raw-colour lines left:', raw.length); raw.forEach((l) => console.log('  ', l.slice(0, 140)));
if (raw.length) process.exit(1);
